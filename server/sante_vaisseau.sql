DROP DATABASE IF EXISTS sante_vaisseau;
CREATE DATABASE sante_vaisseau CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE sante_vaisseau;

CREATE TABLE medecins (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  nom            VARCHAR(100) NOT NULL,
  prenom         VARCHAR(100) NOT NULL,
  specialite     VARCHAR(150) NOT NULL,
  login          VARCHAR(50)  NOT NULL UNIQUE,
  date_creation  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE patients (
  id                       INT AUTO_INCREMENT PRIMARY KEY,
  nom                      VARCHAR(100) NOT NULL,
  prenom                   VARCHAR(100) NOT NULL,
  date_naissance           DATE NOT NULL,
  sexe                     ENUM('M', 'F', 'Autre') NOT NULL,
  login                    VARCHAR(50)  NOT NULL UNIQUE,
  maladie_rythme_cardiaque VARCHAR(200) NULL,
  date_diagnostic          DATE NULL,
  medecin_referent_id      INT NULL,
  date_creation            DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_patient_medecin_referent
    FOREIGN KEY (medecin_referent_id) REFERENCES medecins(id)
    ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE suivi_medecin (
  id                INT AUTO_INCREMENT PRIMARY KEY,
  medecin_id        INT NOT NULL,
  patient_id        INT NOT NULL,
  date_debut_suivi  DATE NOT NULL,
  CONSTRAINT fk_suivi_medecin FOREIGN KEY (medecin_id) REFERENCES medecins(id) ON DELETE CASCADE,
  CONSTRAINT fk_suivi_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  UNIQUE KEY uq_suivi (medecin_id, patient_id)
) ENGINE=InnoDB;

CREATE TABLE mesures_vitales (
  id                    INT AUTO_INCREMENT PRIMARY KEY,
  patient_id            INT NOT NULL,
  date_mesure           DATETIME NOT NULL,
  frequence_cardiaque   SMALLINT NOT NULL,
  spo2                  TINYINT NOT NULL,
  tension_systolique    SMALLINT NOT NULL,
  tension_diastolique   SMALLINT NOT NULL,
  notes                 TEXT NULL,
  CONSTRAINT fk_mesure_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  INDEX idx_mesures_patient_date (patient_id, date_mesure)
) ENGINE=InnoDB;

CREATE TABLE sommeil (
  id                     INT AUTO_INCREMENT PRIMARY KEY,
  patient_id             INT NOT NULL,
  date_nuit              DATE NOT NULL,
  duree_minutes          SMALLINT NOT NULL,
  qualite_pourcentage    TINYINT NOT NULL,
  CONSTRAINT fk_sommeil_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  UNIQUE KEY uq_sommeil_patient_nuit (patient_id, date_nuit)
) ENGINE=InnoDB;

CREATE TABLE journal_medical (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  patient_id     INT NOT NULL,
  medecin_id     INT NULL,
  date_entree    DATETIME NOT NULL,
  contenu        TEXT NOT NULL,
  CONSTRAINT fk_journal_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  CONSTRAINT fk_journal_medecin FOREIGN KEY (medecin_id) REFERENCES medecins(id) ON DELETE SET NULL,
  INDEX idx_journal_patient_date (patient_id, date_entree)
) ENGINE=InnoDB;

CREATE TABLE alertes (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  patient_id     INT NOT NULL,
  niveau         ENUM('ok', 'watch', 'critical') NOT NULL DEFAULT 'ok',
  contenu        TEXT NOT NULL,
  date_creation  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolue        BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_alerte_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  INDEX idx_alertes_patient_niveau (patient_id, niveau)
) ENGINE=InnoDB;

CREATE TABLE chat_messages (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  patient_id     INT NOT NULL,
  expediteur     ENUM('patient', 'ia') NOT NULL,
  contenu        TEXT NOT NULL,
  date_envoi     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chat_patient FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
  INDEX idx_chat_patient_date (patient_id, date_envoi)
) ENGINE=InnoDB;

